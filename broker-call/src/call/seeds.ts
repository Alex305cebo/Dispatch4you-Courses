/**
 * Сиды звонков.
 *
 * Звонок собирается генератором (`makeCall.ts`), но сид берётся не с потолка, а
 * из этого списка. Причина в боевом сервере: промпт там собирает PHP, а PHP не
 * умеет исполнять наш генератор. Заранее известный список позволяет собрать все
 * промпты при сборке (`npm run build:server-config`) и на сервере просто взять
 * готовый — при этом локально тот же сид раскрывается живым генератором в тот
 * же самый звонок.
 *
 * Шестьдесят разных брокеров с разными грузами против восьми записанных руками
 * сценариев. Расширять — дописывать строки: всё остальное сгенерируется само.
 */
export const CALL_SEEDS: readonly string[] = Array.from(
  { length: 60 },
  (_, i) => `call-${String(i + 1).padStart(3, '0')}`,
)

/** Случайный звонок. Именно здесь берётся разнообразие, видимое студенту. */
export function randomSeed(): string {
  return CALL_SEEDS[Math.floor(Math.random() * CALL_SEEDS.length)] ?? CALL_SEEDS[0]!
}
